type authConsumerFactory func(context.Context, authconsumer.Config, *http.Client) (*authconsumer.Client, error)

func configureAuthConsumer(hV1 *handlerv1.Handler, cfg config.Config, localMode bool, factory authConsumerFactory) (*authconsumer.Client, error) {
	hV1.SetAuthManagementBridge(cfg.BFFManagementBridge)
	if localMode {
		return nil, nil
	}
	consumer := cfg.BFFAuthConsumer
	if consumer == nil || strings.TrimSpace(consumer.Environment) == "" || strings.TrimSpace(consumer.AuthURL) == "" ||
		strings.TrimSpace(consumer.Issuer) == "" || strings.TrimSpace(consumer.VerifierAudience) == "" ||
		strings.TrimSpace(consumer.Resource) == "" || consumer.TimeoutSeconds != 5 {
		return nil, errors.New("Auth consumer identity is missing from BFF config")
	}
	switch cfg.BFFConfigSchemaVersion {
	case 2:
		if !cfg.BFFManagementBridge {
			return nil, errors.New("schema-2 Auth consumer bridge is unavailable")
		}
	case 3:
		if cfg.BFFManagementBridge {
			return nil, errors.New("schema-3 BFF cannot enable legacy management bridge")
		}
	default:
		return nil, errors.New("BFF Auth consumer schema is unsupported")
	}
	if factory == nil {
		return nil, errors.New("Auth consumer factory is unavailable")
	}
	runtimeConfig := authconsumer.Config{
		BaseURL: consumer.AuthURL, Environment: consumer.Environment, Issuer: consumer.Issuer,
		Resource: consumer.Resource, Audience: consumer.VerifierAudience,
		VerifierPath: consumer.VerifierPath, AccountCheckPath: consumer.AccountCheckPath, CatalogPath: consumer.CatalogPath,
		Timeout: time.Duration(consumer.TimeoutSeconds) * time.Second,
	}
	client, err := factory(context.Background(), runtimeConfig, &http.Client{Timeout: runtimeConfig.Timeout})
	if err != nil {
		return nil, fmt.Errorf("configure Auth consumer: %w", err)
	}
	hV1.SetConsumerVerifier(client)
	return client, nil
}

func main() {
	cfg, err := config.LoadBFFFile(os.Getenv("LWC_BFF_CONFIG_PATH"))
	if err != nil {
		log.Fatalf("Failed to load config: %v", err)
	}
	var stageConfig *queryconfig.Config
	if cfg.QueryStageConfigPath != "" {
		loaded, err := queryconfig.LoadFile(cfg.QueryStageConfigPath)
		if err != nil {
			log.Fatalf("Failed to load query stage config: %v", err)
		}
		stageConfig = &loaded
		log.Printf("Query stage config: schema=%d revision=%s digest=%s", loaded.SchemaVersion, loaded.ConfigRevision, loaded.ConfigDigest)
	}

	localMode := cfg.LocalCloudScope != ""
	if localMode && strings.TrimSpace(cfg.JWTSecret) == "" {
		log.Fatal("local cloud signing key is missing")
	}
	gcsClient, err := gcs.NewClientWithScope(cfg.Bucket, cfg.LocalCloudScope)
	if err != nil {
		log.Fatalf("Failed to create GCS client: %v", err)
	}
	defer gcsClient.Close()
	wikiStore := store.RootStore(gcsClient)
	log.Printf("GCS target ready: gs://%s/%s", cfg.Bucket, cfg.LocalCloudScope)

	// Init Firestore client
	fsClient, err := firestore.NewClientWithDatabaseAndScope(cfg.GCPProject, cfg.FirestoreDatabaseID, "", "", cfg.LocalCloudScope)
	if err != nil {
		log.Fatalf("Failed to create Firestore client: %v", err)
	}
	defer fsClient.Close()
	if localMode {
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		checkErr := errors.Join(fsClient.CheckAvailable(ctx), gcsClient.CheckAvailable(ctx))
		cancel()
		if checkErr != nil {
			log.Fatalf("local cloud target is unavailable: %v", checkErr)
		}
	}

	// Search metadata index
	idx := search.NewIndex()
	log.Printf("Search metadata index: not yet rebuilt — call /api/v1/pipeline/rebuild-index")
	log.Printf("Concept bodies: not yet rebuilt — call /api/v1/pipeline/rebuild-index")

	// Project-scoped concept cache for the V1 query path.
	conceptCache := conceptcache.New()
	log.Printf("Concept cache: not yet rebuilt — call /api/v1/pipeline/rebuild-index")

	productionExecutor, err := newProductionQueryExecutorWithStageConfig(cfg, conceptCache, stageConfig)
	if err != nil {
		log.Fatalf("Failed to create production query executor: %v", err)
	}
	build := buildinfo.Current()
	log.Printf("Build identity: commit=%s service=%s revision=%s", build.Commit, build.Service, build.Revision)
	slog.SetDefault(slog.New(slog.NewJSONHandler(os.Stdout, nil)))
	traceProvider, traceErr := observability.InitTracesWithProject(build.Service, build.Revision, cfg.GCPProject)
	if traceErr != nil {
		log.Printf("[observability] WARNING: trace init failed (continuing)")
	} else {
		defer observability.ShutdownTraces(traceProvider)
	}

	// OpenTelemetry metrics (graceful fallback)
	provider, err := observability.InitMetrics(context.Background(), observabilityServiceName(os.Getenv("K_SERVICE")), cfg.GCPProject)
	if err != nil {
		log.Printf("[observability] WARNING: metrics init failed (continuing): %v", err)
	} else {
		defer func() {
			if err := provider.Shutdown(context.Background()); err != nil {
				log.Printf("[observability] metrics shutdown error: %v", err)
			}
		}()
	}

	// Handlers
	hV1 := handlerv1.New(wikiStore, fsClient, idx, conceptCache, nil, nil)
	authConsumerClient, err := configureAuthConsumer(hV1, cfg, localMode, authconsumer.NewGoogleRuntime)
	if err != nil {
		log.Fatalf("configure Auth consumer: %v", err)
	}
	hV1.SetMCPConfig(cfg.MCP)
	hV1.SetQueryExecutor(productionExecutor)
	hV1.SetPipelineJobURL(cfg.PipelineJobURL)
	hV1.SetPipelineQuotaConfig(
		cfg.PipelineDailyLimit,
		cfg.PipelineCooldownSeconds,
		cfg.PipelineMinNewRaw,
		cfg.PipelineDemoUserIDs,
	)
	configureScheduledPipeline(hV1, cfg)
	settingsStore := syssettings.NewStore(fsClient.Raw(), cfg.RegistrationEnabled)
	var nativeWorker *localpipeline.Manager
	if localMode {
		workerPath := strings.TrimSpace(cfg.LocalWorkerPath)
		if workerPath == "" {
			log.Fatal("LOCAL_CLOUD_WORKER_PATH is required for local cloud pipeline execution")
		}
		workerInfo, statErr := os.Stat(workerPath)
		if statErr != nil || workerInfo.IsDir() || workerInfo.Mode()&0111 == 0 {
			log.Fatal("local cloud worker binary is unavailable or not executable")
		}
		if _, err := exec.LookPath(workerPath); err != nil {
			log.Fatalf("local cloud worker binary is not executable: %v", err)
		}
		nativeWorker, err = localpipeline.New(localpipeline.Config{
			Firestore: fsClient.Raw(), Storage: gcsClient, Worker: workerPath,
			Project: cfg.GCPProject, Bucket: cfg.Bucket, Database: cfg.FirestoreDatabaseID,
			Scope: cfg.LocalCloudScope, WorkDir: ".",
			PipelineConfigPath:   cfg.LocalPipelineConfigPath,
			PipelineBindingsPath: cfg.LocalPipelineBindingsPath,
		})
		if err != nil {
			log.Fatalf("configure local pipeline executor: %v", err)
		}
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		err = nativeWorker.ReconcileInterrupted(ctx)
		cancel()
		if err != nil {
			log.Fatalf("reconcile interrupted local pipeline records: %v", err)
		}
		hV1.SetLocalPipelineExecutor(nativeWorker)
	}

	intakeService := newURLIntakeService(cfg, func(scope urlintake.ActorProject) (urlintake.ProjectStore, error) {
		if gcsClient == nil || strings.TrimSpace(scope.ActorID) == "" || strings.TrimSpace(scope.ProjectID) == "" {
			return nil, errors.New("scoped raw storage is unavailable")
		}
		return gcsClient.WithScope(scope.ActorID, scope.ProjectID), nil
	})
	hV1.SetURLIntakeService(intakeService)
	rawFactory := func(scopedClient *gcs.Client, fsClient *firestore.Client) rawScrapeHandler {
		return handlerraw.NewWithURLIntake(scopedClient, fsClient, intakeService)
	}
	var publicRegistrationProvider syssettings.PublicRegistrationSettingsProvider
	if authConsumerClient != nil {
		publicRegistrationProvider = authConsumerPublicRegistrationProvider{client: authConsumerClient}
	}
	r := newProductionRouter(cfg, localMode, gcsClient, fsClient, hV1, settingsStore, rawFactory, publicRegistrationProvider)

	listenHost := ":"
	if localMode {
		listenHost = "127.0.0.1:"
	}
	log.Printf("BFF listening on %s%s", listenHost, cfg.Port)
	log.Printf("Swagger UI: http://localhost:%s/swagger/index.html", cfg.Port)
	server := &http.Server{Addr: listenHost + cfg.Port, Handler: r, ReadHeaderTimeout: 10 * time.Second}
	serveErr := make(chan error, 1)
	go func() { serveErr <- server.ListenAndServe() }()
	stop, stopSignal := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stopSignal()
	if localMode && nativeWorker != nil {
		go nativeWorker.RunQuotaReconciler(stop)
		go hV1.RunPipelineQuotaReconciler(stop)
	} else {
		go hV1.RunPipelineQuotaReconciler(stop)
	}
	select {
	case err := <-serveErr:
		if err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Printf("BFF server stopped: %v", err)
		}
	case <-stop.Done():
	}
	if err := shutdownBFF(server, nativeWorker, 15*time.Second, 15*time.Second); err != nil {
		log.Printf("BFF shutdown: %v", err)
	}
}

