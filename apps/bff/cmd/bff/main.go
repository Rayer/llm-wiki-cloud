func localAuthHostAllowlist(cfg config.Config) gin.HandlerFunc {
	allowed := make(map[string]struct{})
	for _, host := range cfg.AllowedHostsFor(true) {
		allowed[strings.ToLower(strings.TrimSpace(host))] = struct{}{}
	}
	return func(c *gin.Context) {
		host := strings.ToLower(strings.TrimSpace(c.Request.Host))
		if parsed, _, err := net.SplitHostPort(host); err == nil {
			host = parsed
		}
		if _, ok := allowed[host]; !ok {
			c.AbortWithStatusJSON(http.StatusBadRequest, gin.H{"error": "invalid Host header"})
			return
		}
		c.Next()
	}
}

func newProductionRouter(
	cfg config.Config,
	localMode bool,
	gcsClient *gcs.Client,
	fsClient *firestore.Client,
	hV1 *handlerv1.Handler,
	settingsStore syssettings.RegistrationGate,
	rawScrapeFactory rawScrapeHandlerFactory,
) *gin.Engine {
	r := gin.Default()
	r.Use(middleware.SecurityHeaders(true))

	// OpenTelemetry latency middleware (per-endpoint)
	r.Use(middleware.LatencyMiddleware())

	// CORS — must be BEFORE routes
	allowOrigins := cfg.AllowedOriginsFor(localMode)
	r.Use(cors.New(cors.Config{
		AllowOrigins:     allowOrigins,
		AllowMethods:     []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"},
		AllowHeaders:     []string{"Content-Type", "Authorization", "X-Project-ID", "Idempotency-Key"},
		AllowCredentials: true,
	}))

	registerPublicRoutes(r, settingsStore, cfg.AuthServiceURL, !localMode)
	r.POST("/internal/profile/dispatch", productionProfileDispatcher(hV1, cfg).Gin)
	r.GET("/api/v1/query/config", hV1.QueryConfig)

	// Temporary Stage A compatibility lane for the frontend Auth cutover.
	var sessions *auth.RefreshSessionAuthority
	authRoutes := r.Group("/api/v1/auth")
	if localMode {
		authRoutes.Use(localAuthHostAllowlist(cfg))
	}
	authRoutes.Use(auth.CompatibilityBodyLimit())
	cookiePolicy := auth.LegacyRefreshCookiePolicy()
	if localMode {
		cookiePolicy = auth.LocalRefreshCookiePolicy()
	}
	if fsClient == nil || fsClient.Raw() == nil {
		unavailable := func(c *gin.Context) {
			c.JSON(http.StatusServiceUnavailable, gin.H{"error": "auth routes require Firestore"})
		}
		authRoutes.POST("/login", unavailable)
		authRoutes.POST("/register", unavailable)
		authRoutes.POST("/refresh", unavailable)
		authRoutes.POST("/logout", auth.LogoutHandlerWithCookiePolicy(cookiePolicy))
	} else {
		identityRepository := auth.NewIdentityRepository(fsClient.Raw())
		sessionEnvironment := strings.TrimSpace(cfg.AuthSessionEnvironment)
		if sessionEnvironment == "" {
			sessionEnvironment = strings.TrimSpace(cfg.FirestoreDatabaseID)
			if sessionEnvironment == "" {
				sessionEnvironment = "default"
			}
		}
		sessions = auth.NewRefreshSessionAuthorityWithConfig(fsClient.Raw(), auth.SessionAuthorityConfig{
			Environment: sessionEnvironment, Migration: auth.RefreshSessionMigrationMode(cfg.AuthSessionMigration),
		})
		authRoutes.POST("/login", middleware.NewRateLimiter(10, time.Minute), auth.LoginHandlerWithRepositoryAndSessionAuthority(identityRepository, cfg.JWTSecret, cookiePolicy, sessions))
		authRoutes.POST("/register", middleware.NewRateLimiter(5, time.Minute), auth.RegisterHandlerWithRepository(identityRepository, cfg.JWTSecret, settingsStore))
		authRoutes.POST("/refresh", auth.RefreshHandlerWithSessionAuthority(sessions, cfg.JWTSecret, cookiePolicy))
		authRoutes.POST("/logout", auth.LogoutHandlerWithSessionAuthority(sessions, cfg.JWTSecret, cookiePolicy))
	}
	if fsClient == nil {
		wireCLIAuthorities(hV1, nil, sessions)
	} else {
		wireCLIAuthorities(hV1, fsClient.Raw(), sessions)
	}

	// ── Swagger UI ──
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// ── API v1 (with JWT auth + project routing) ──
	v1 := r.Group("/api/v1")

	v1.Use(hV1.AccountAuth(cfg))
	{
		v1.GET("/health", hV1.Health)
		v1.GET("/ready", hV1.Ready)
		v1.GET("/projects", hV1.ListProjects)
		v1.POST("/init-project", hV1.InitProject)
		v1.PATCH("/projects/:projectID", hV1.RenameProject)
		v1.GET("/projects/:pid/status", hV1.ProjectStatus)
	}

	registerAdminRoutes(r, cfg, hV1, settingsStore)

	v1.Use(auth.ProjectMiddleware())
	{
		v1.POST("/pipeline/rebuild-index", hV1.RebuildIndex)
		v1.GET("/projects/:pid/recompile-all/capability", hV1.RecompileAllCapability)
		v1.POST("/projects/:pid/recompile-all", hV1.RecompileAll)
		profileRoutes := v1.Group("")
		profileRoutes.Use(hV1.TrialDemoAccessGuard())
		profileRoutes.GET("/projects/:pid/profile", hV1.GetProfile)
		profileRoutes.PUT("/projects/:pid/profile", hV1.PutProfile)
		profileRoutes.GET("/projects/:pid/profile/bootstrap-guidance", hV1.GetProfileBootstrapGuidance)
		profileRoutes.GET("/projects/:pid/profile/guidance/:revision", hV1.GetProfileGuidanceArtifact)
		profileRoutes.POST("/projects/:pid/profile/bootstrap-guidance/:revision/confirm", hV1.ConfirmProfileBootstrapGuidance)
		profileRoutes.POST("/projects/:pid/profile/candidates/:candidateID/confirm", hV1.ConfirmProfileCandidate)
		profileRoutes.POST("/projects/:pid/profile/candidates/:candidateID/retry", hV1.RetryProfileCandidate)
		profileRoutes.POST("/projects/:pid/profile/derivation/retry", hV1.RetryProfileDerivation)
		profileRoutes.GET("/projects/:pid/profile/jobs/:jobID", hV1.GetProfileJob)
		var exportRepo exportjob.Repository
		var projectVerifier exportjob.ProjectVerifier
		var archiveStore *exportjob.CloudArchiveStore
		if fsClient != nil && fsClient.Raw() != nil {
			exportRepo = exportjob.NewFirestoreRepository(fsClient.Raw())
			projectVerifier = exportjob.NewFirestoreProjectVerifier(fsClient.Raw())
		}
		if !localMode && cfg.Bucket != "" && cfg.ExportSigningServiceAccount != "" {
			var err error
			archiveStore, err = exportjob.NewCloudArchiveStore(context.Background(), cfg.Bucket, cfg.ExportSigningServiceAccount)
			if err != nil {
				log.Printf("WARNING: export storage unavailable: %v", err)
			}
		}
		exportHandler := newExportHTTPHandler(localMode, cfg, exportRepo, projectVerifier, archiveStore)
		exportRoutes := v1.Group("")
		exportRoutes.Use(hV1.TrialDemoAccessGuard())
		exportHandler.Register(exportRoutes)

		v1.GET("/index", hV1.Index)
		v1.POST("/query", hV1.Query)
		v1.GET("/sources", hV1.ListSources)
		v1.GET("/sources/:id/annotation", hV1.GetAnnotation)
		v1.PUT("/sources/:id/annotation", hV1.PutAnnotation)
		v1.GET("/sources/:id", hV1.GetSource)
		v1.GET("/concepts", hV1.ListConcepts)
		v1.GET("/concepts/:id", hV1.GetConcept)
		v1.POST("/import", hV1.Import)
		v1.POST("/pipeline/run", hV1.PipelineRun)
		v1.GET("/pipeline/status", hV1.PipelineStatus)
		v1.GET("/pipeline/log", hV1.PipelineLog)
		registerRawScrapeRoute(v1, gcsClient, fsClient, rawScrapeFactory)
		v1.GET("/raw", hV1.RawList)
		v1.GET("/raw/:filename", hV1.RawPreview)
		v1.POST("/raw/upload", hV1.RawUpload)
		v1.GET("/status", hV1.Status)
		v1.GET("/metrics", hV1.PrometheusMetrics)
	}

	// ── Static frontend ──
	r.StaticFile("/", "./static/index.html")
	r.Static("/static", "./static")
	r.NoRoute(func(c *gin.Context) {
		// SPA fallback: serve index.html for non-API routes
		if !strings.HasPrefix(c.Request.URL.Path, "/api") {
			c.File("./static/index.html")
		}
	})

	return r
}

