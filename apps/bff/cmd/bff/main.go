func main() {
	cfg, err := config.Load(".")
	if err != nil {
		log.Fatalf("Failed to load config: %v", err)
	}
	var stageConfig *queryconfig.Config
	if cfg.QueryStageConfigPath != "" {
		loaded, err := queryconfig.LoadFile(cfg.QueryStageConfigPath)
		if err != nil {
			log.Fatalf("Failed to load query stage config: %v", err)
		}
		stageConfig = &loaded
		log.Printf("Query stage config: schema=%d revision=%s digest=%s", loaded.SchemaVersion, loaded.ConfigRevision, loaded.ConfigDigest)
	}

	localMode := cfg.LocalCloudScope != ""
	if localMode && strings.TrimSpace(cfg.JWTSecret) == "" {
		log.Fatal("local cloud signing key is missing")
	}
	gcsClient, err := gcs.NewClient(cfg.Bucket)
	if err != nil {
		log.Fatalf("Failed to create GCS client: %v", err)
	}
	defer gcsClient.Close()
	wikiStore := store.RootStore(gcsClient)
	log.Printf("GCS target ready: gs://%s/%s", cfg.Bucket, cfg.LocalCloudScope)

	// Init Firestore client
	fsClient, err := firestore.NewClientWithDatabase(cfg.GCPProject, cfg.FirestoreDatabaseID, "", "")
	if err != nil {
		log.Fatalf("Failed to create Firestore client: %v", err)
	}
	defer fsClient.Close()
	if localMode {
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		checkErr := errors.Join(fsClient.CheckAvailable(ctx), gcsClient.CheckAvailable(ctx))
		cancel()
		if checkErr != nil {
			log.Fatalf("local cloud target is unavailable: %v", checkErr)
		}
	}

	// Search metadata index
	idx := search.NewIndex()
	log.Printf("Search metadata index: not yet rebuilt — call /api/v1/pipeline/rebuild-index")
	log.Printf("Concept bodies: not yet rebuilt — call /api/v1/pipeline/rebuild-index")

	// Project-scoped concept cache for the V1 query path.
	conceptCache := conceptcache.New()
	log.Printf("Concept cache: not yet rebuilt — call /api/v1/pipeline/rebuild-index")

	productionExecutor, err := newProductionQueryExecutorWithStageConfig(cfg, conceptCache, stageConfig)
	if err != nil {
		log.Fatalf("Failed to create production query executor: %v", err)
	}
	build := buildinfo.Current()
	log.Printf("Build identity: commit=%s service=%s revision=%s", build.Commit, build.Service, build.Revision)

	// OpenTelemetry metrics (graceful fallback)
	provider, err := observability.InitMetrics(context.Background(), observabilityServiceName(os.Getenv("K_SERVICE")), observability.GetProjectID())
	if err != nil {
		log.Printf("[observability] WARNING: metrics init failed (continuing): %v", err)
	} else {
		defer func() {
			if err := provider.Shutdown(context.Background()); err != nil {
				log.Printf("[observability] metrics shutdown error: %v", err)
			}
		}()
	}

	// Handlers
	hV1 := handlerv1.New(wikiStore, fsClient, idx, conceptCache, nil, nil)
	hV1.SetQueryExecutor(productionExecutor)
	hV1.SetPipelineJobURL(cfg.PipelineJobURL)
	hV1.SetPipelineQuotaConfig(
		cfg.PipelineDailyLimit,
		cfg.PipelineCooldownSeconds,
		cfg.PipelineMinNewRaw,
		cfg.PipelineDemoUserIDs,
	)
	settingsStore := syssettings.NewStore(fsClient.Raw(), cfg.RegistrationEnabled)
	var nativeWorker *localpipeline.Manager
	if localMode {
		workerPath := strings.TrimSpace(os.Getenv("LOCAL_CLOUD_WORKER_PATH"))
		if workerPath == "" {
			log.Fatal("LOCAL_CLOUD_WORKER_PATH is required for local cloud pipeline execution")
		}
		workerPath, err = filepath.Abs(workerPath)
		if err != nil {
			log.Fatalf("resolve local worker path: %v", err)
		}
		workerInfo, statErr := os.Stat(workerPath)
		if statErr != nil || workerInfo.IsDir() || workerInfo.Mode()&0111 == 0 {
			log.Fatal("local cloud worker binary is unavailable or not executable")
		}
		if _, err := exec.LookPath(workerPath); err != nil {
			log.Fatalf("local cloud worker binary is not executable: %v", err)
		}
		nativeWorker, err = localpipeline.New(localpipeline.Config{
			Firestore: fsClient.Raw(), Storage: gcsClient, Worker: workerPath,
			Project: cfg.GCPProject, Bucket: cfg.Bucket, Database: cfg.FirestoreDatabaseID,
			Scope: cfg.LocalCloudScope, WorkDir: ".",
			PipelineConfigPath:   os.Getenv("LOCAL_CLOUD_PIPELINE_CONFIG_PATH"),
			PipelineBindingsPath: os.Getenv("LOCAL_CLOUD_PIPELINE_BINDINGS_PATH"),
		})
		if err != nil {
			log.Fatalf("configure local pipeline executor: %v", err)
		}
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		err = nativeWorker.ReconcileInterrupted(ctx)
		cancel()
		if err != nil {
			log.Fatalf("reconcile interrupted local pipeline records: %v", err)
		}
		hV1.SetLocalPipelineExecutor(nativeWorker)
	}

	r := newProductionRouter(cfg, localMode, gcsClient, fsClient, hV1, settingsStore, defaultRawScrapeHandlerFactory)

	listenHost := ":"
	if localMode {
		listenHost = "127.0.0.1:"
	}
	log.Printf("BFF listening on %s%s", listenHost, cfg.Port)
	log.Printf("Swagger UI: http://localhost:%s/swagger/index.html", cfg.Port)
	server := &http.Server{Addr: listenHost + cfg.Port, Handler: r, ReadHeaderTimeout: 10 * time.Second}
	serveErr := make(chan error, 1)
	go func() { serveErr <- server.ListenAndServe() }()
	stop, stopSignal := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stopSignal()
	if localMode && nativeWorker != nil {
		go nativeWorker.RunQuotaReconciler(stop)
	} else {
		go hV1.RunPipelineQuotaReconciler(stop)
	}
	select {
	case err := <-serveErr:
		if err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Printf("BFF server stopped: %v", err)
		}
	case <-stop.Done():
	}
	if err := shutdownBFF(server, nativeWorker, 15*time.Second, 15*time.Second); err != nil {
		log.Printf("BFF shutdown: %v", err)
	}
}

type localPipelineCloser interface {
	Close(context.Context) error
}

func shutdownBFF(server *http.Server, nativeWorker localPipelineCloser, httpTimeout, workerTimeout time.Duration) error {
	var shutdownErrors []error
	httpCtx, cancelHTTP := context.WithTimeout(context.Background(), httpTimeout)
	if err := server.Shutdown(httpCtx); err != nil {
		shutdownErrors = append(shutdownErrors, fmt.Errorf("shut down HTTP server: %w", err))
		if closeErr := server.Close(); closeErr != nil {
			shutdownErrors = append(shutdownErrors, fmt.Errorf("force close HTTP server: %w", closeErr))
		}
	}
	cancelHTTP()
	if manager, ok := nativeWorker.(*localpipeline.Manager); ok && manager == nil {
		nativeWorker = nil
	}
	if nativeWorker != nil {
		workerCtx, cancelWorker := context.WithTimeout(context.Background(), workerTimeout)
		if err := nativeWorker.Close(workerCtx); err != nil {
			shutdownErrors = append(shutdownErrors, fmt.Errorf("stop local worker: %w", err))
		}
		cancelWorker()
	}
	return errors.Join(shutdownErrors...)
}

func newProductionQueryExecutor(cfg config.Config, conceptCache *conceptcache.Cache) (query.Executor, error) {
	var stageConfig *queryconfig.Config
	if cfg.QueryStageConfigPath != "" {
		loaded, err := queryconfig.LoadFile(cfg.QueryStageConfigPath)
		if err != nil {
			return nil, err
		}
		stageConfig = &loaded
	}
	return newProductionQueryExecutorWithStageConfig(cfg, conceptCache, stageConfig)
}

func newProductionQueryExecutorWithStageConfig(cfg config.Config, conceptCache *conceptcache.Cache, stageConfig *queryconfig.Config) (query.Executor, error) {
	if cfg.QueryStageConfigPath != "" && stageConfig == nil {
		return nil, errors.New("query stage config was not loaded")
	}
	if stageConfig != nil {
		sealed := *stageConfig
		expansionTemperature := sealed.Stages.QueryExpander.Temperature
		expansionClient := llm.NewClientWithOptions(cfg.DeepSeekAPIKey, llm.ClientOptions{
			Model: sealed.Stages.QueryExpander.Model, Temperature: &expansionTemperature,
			Reasoning: llm.Reasoning(sealed.Stages.QueryExpander.Reasoning),
		})
		if expansionClient == nil {
			return nil, errors.New("invalid sealed query expansion client configuration")
		}
		synthesisTemperature := sealed.Stages.AnswerSynthesizer.Temperature
		synthesisClient := llm.NewClientWithOptions(cfg.DeepSeekAPIKey, llm.ClientOptions{
			Model: sealed.Stages.AnswerSynthesizer.Model, Temperature: &synthesisTemperature,
			Reasoning: llm.Reasoning(sealed.Stages.AnswerSynthesizer.Reasoning),
		})
		if synthesisClient == nil {
			return nil, errors.New("invalid sealed query synthesis client configuration")
		}
		synthesisService := query.NewService(conceptCache, nil, synthesisClient)
		runtime, err := queryruntime.NewExecutor(sealed, conceptCache, expansionClient, nil, synthesisService)
		if err != nil {
			return nil, err
		}
		return runtime, nil
	}

	selectionLimit := cfg.QuerySelectionLimit
	if selectionLimit == 0 {
		selectionLimit = config.DefaultQuerySelectionLimit
	}
	explorationSlots := cfg.QuerySelectionExplorationSlots
	if cfg.QuerySelectionLimit == 0 && explorationSlots == 0 {
		explorationSlots = config.DefaultQuerySelectionExplorationSlots
	}
	evidenceThreshold := cfg.QuerySelectionEvidenceThreshold
	evidenceThresholdSet := cfg.QuerySelectionEvidenceThreshold != 0
	if evidenceThreshold == 0 {
		evidenceThreshold = config.DefaultQuerySelectionEvidenceThreshold
	}
	if cfg.QueryExpansionModel == "" {
		cfg.QueryExpansionModel = config.DefaultQueryExpansionModel
	}
	if cfg.AnswerSynthesisModel == "" {
		cfg.AnswerSynthesisModel = config.DefaultAnswerSynthesisModel
	}
	if cfg.AnswerSynthesisReasoning == "" {
		cfg.AnswerSynthesisReasoning = config.DefaultAnswerSynthesisReasoning
	}
	if cfg.QueryExpansionModel != "" && cfg.QueryExpansionModel != config.DefaultQueryExpansionModel {
		return nil, fmt.Errorf("query expansion model must be %s", config.DefaultQueryExpansionModel)
	}
	synthesisClient := llm.NewClientWithOptions(cfg.DeepSeekAPIKey, llm.ClientOptions{Model: cfg.AnswerSynthesisModel, Reasoning: cfg.AnswerSynthesisReasoning})
	if cfg.DeepSeekAPIKey != "" && synthesisClient == nil {
		return nil, errors.New("invalid answer synthesis client configuration")
	}
	temperature := 0.0
	expansionClient := llm.NewClientWithOptions(cfg.DeepSeekAPIKey, llm.ClientOptions{Model: cfg.QueryExpansionModel, Temperature: &temperature, Reasoning: config.DefaultQueryExpansionReasoning})
	var expansionProvider queryquality.ChatProvider
	if expansionClient != nil {
		expansionProvider = expansionClient
	}
	legacyExpander, err := llm.NewExpander(nil, "lifestyle")
	if err != nil {
		return nil, err
	}
	legacy := query.NewService(conceptCache, legacyExpander, synthesisClient)
	return queryquality.NewProductionExecutor(conceptCache, expansionProvider, legacy, legacy, queryquality.Options{
		SelectionLimit: selectionLimit, ExplorationSlots: explorationSlots,
		EvidenceThreshold: evidenceThreshold, EvidenceThresholdSet: evidenceThresholdSet,
		KeywordsPerAttempt:    cfg.QueryExpansionKeywordsPerAttempt,
		ExpansionAttempts:     cfg.QueryExpansionAttempts,
		RareDocumentFrequency: cfg.QueryMatchingRareKeywordMaxDocumentFrequency,
	})
}

